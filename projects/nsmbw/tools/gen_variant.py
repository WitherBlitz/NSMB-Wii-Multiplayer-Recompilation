"""Per-version tables for a build: E1 (USA rev 1) addresses -> the variant's.

    python gen_variant.py <variant> <build dir> [--map <address-map.txt>] [--game <dir>]
                          [--canonical-game <dir>] [--no-verify]

Writes <build dir>/variant/:
  nsmbw_va_table.inc   E1 -> variant ranges, {e1_start, e1_end, target}, for NSMBW_VA()
  nsmbw_va_tokens.h    #define NSMBW_VA_TOK_<e1> <target> for every bare-hex token the runtime's
                       hook macros paste (PPC_NATIVE_OVERRIDE(801A1138, ...) and the like)
  addr_map.tsv         the same ranges for the translator (recomp.yml runtime.address_map)
  variant.h            the variant's facts: ID, revision, region, SDA bases, entry, REL layout
  recomp.yml           the translator project for the variant (not for E1: projects/nsmbw/recomp.yml)
  MAP.txt              the function map for the variant (not for E1: projects/nsmbw/MAP.txt)
  gen_<v>.txt          what was generated and from what
and then runs verify_variant.py into the same folder (a failure exits non-zero).

The table is the address map's strict E1 -> variant mapping, then variants/<v>/overrides.tsv, then
the p1_character stub area computed from the variant's REL chain. The SDA bases and the entry point
come from the variant's main.dol (the map has no entry for _SDA_BASE_), the REL bases from chaining
the variant's RELs. For E1 everything is the identity and neither the map nor a game is needed.

MAP.txt: every E1 function start that maps, under its E1 name, plus every b/bl target and REL
entry the variant's own code has (where its region-specific code is); both lists are compared in
gen_<v>.txt. --game is the variant's unpack_game.py folder (default: its game_dir) or a Dolphin
extract, read in memory.
"""
import bisect
import sys
from pathlib import Path

import p1_character
import prelink_rels
import runtime_scan
import variants
import verify_variant
from variant_image import Image

GENERATED_HEADER = "Generated by projects/nsmbw/tools/gen_variant.py for {v} ({gid} rev {rev}). Do not edit."


def token_target(token, target):
    """The target spelled like the token (the macros paste it into func_<token>)."""
    text = f"{target:08X}"
    return text.lower() if any(c in "abcdef" for c in token) else text


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    if not path.exists() or path.read_bytes() != data:  # unchanged files keep their time stamps
        path.write_bytes(data)


TERMINATORS = {0x4E800020, 0x4C000064, 0x4E800420}  # blr, rfi, bctr


def function_map(e1_starts, e1_names, results, table, tg):
    """(lines, report) for the variant's MAP.txt. results: verify_variant.equivalence's."""
    mapped, unmapped, proven = {}, [], []
    for idx, s in enumerate(e1_starts):
        t = table.lookup(s)
        if t is None:
            unmapped.append(s)
            continue
        name = e1_names.get(s, "")
        if not name or name == f"0x{s:08x}":
            name = f"0x{t:08x}"
        mapped[t] = name
        if results.get(s, ("",))[0] in verify_variant.PROVEN + ("differs",):
            nxt = e1_starts[idx + 1] if idx + 1 < len(e1_starts) else s + 4
            proven.append((t, t + 4 * max(1, min((nxt - s) // 4, verify_variant.MAX_WORDS))))
    proven.sort()
    proven_starts = [a for a, _b in proven]

    def inside_proven(a):
        """Inside the body of an E1 function that maps (the same code, or the same function with
        some words changed): E1's analysis already decided which addresses in there are function
        starts, and a pointer into one is a switch's case label."""
        i = bisect.bisect_right(proven_starts, a) - 1
        return i >= 0 and proven[i][0] < a < proven[i][1]

    def code(a):
        return a & 3 == 0 and tg.kind(a) == "text" and bool(tg.word(a))

    def plausible(a):
        """After a terminator or the zero padding that follows one, and not text (strings)."""
        p = a - 4
        while tg.word(p) == 0 and a - p < 0x40:
            p -= 4
        prev = tg.word(p) or 0
        ascii_like = all(0x20 <= b <= 0x7E for b in tg.word(a).to_bytes(4, "big"))
        return (prev in TERMINATORS or (prev >> 26 == 18 and not prev & 1)) and not ascii_like

    calls, pointers = set(), set()
    for lo, hi in tg.exec_ranges():
        calls.add(lo)
        for a in range(lo, hi, 4):
            w = tg.word(a)
            if w is None:
                continue
            if w >> 26 == 18 and w & 1:
                d = w & 0x03FFFFFC
                d -= (d & 0x02000000) * 2
                dst = (d if w & 2 else a + d) & 0xFFFFFFFF
                if code(dst):
                    calls.add(dst)  # bl: a call is a function start
            elif w >> 26 == 15 and (w >> 16) & 31 == 0 and not inside_proven(a):
                rd = (w >> 21) & 31  # lis rD + addi/ori rD: a code pointer built in differing code
                for b in range(a + 4, min(a + 36, hi), 4):
                    x = tg.word(b)
                    if x >> 26 == 14 and (x >> 16) & 31 == rd:
                        pointers.add(((w & 0xFFFF) << 16) + (x & 0xFFFF) - (0x10000 if x & 0x8000 else 0) & 0xFFFFFFFF)
                        break
                    if x >> 26 == 24 and (x >> 21) & 31 == rd:
                        pointers.add((w & 0xFFFF) << 16 | x & 0xFFFF)
                        break
    calls.update(a for a in tg.rel_entries() if code(a))
    for a, b, k in tg.spans:
        if k != "data":
            continue
        for p in range(a, b - 3, 4):
            w = tg.word(p)
            if w and w & 3 == 0 and tg.kind(w) == "text":
                pointers.add(w)  # vtables, profile tables, callbacks
    new_calls = sorted(calls - set(mapped))
    new_pointers = sorted(a for a in pointers - set(mapped) - calls
                          if code(a) and not inside_proven(a) and plausible(a))
    starts = dict(mapped)
    for a in new_calls + new_pointers:
        starts[a] = f"0x{a:08x}"
    lines = [f"{a:08x} {starts[a]}\n" for a in sorted(starts)]
    report = [f"MAP.txt: {len(starts)} function starts: {len(mapped)} of {len(e1_starts)} E1 starts mapped "
              f"({len(unmapped)} do not map); found only in the variant's code: {len(new_calls)} call targets "
              f"and REL entries, {len(new_pointers)} code pointers (outside every mapped E1 function)"]
    report += [f"  E1 start with no mapping: 0x{s:08X} {e1_names.get(s, '')}" for s in unmapped]
    report += [f"  variant-only start (call): 0x{a:08X}" for a in new_calls[:100]]
    report += [f"  variant-only start (pointer): 0x{a:08X}" for a in new_pointers[:100]]
    return lines, report


def main():
    argv = sys.argv[1:]
    opts = {}
    for flag in ("--map", "--game", "--canonical-game"):
        if flag in argv:
            at = argv.index(flag)
            opts[flag] = argv[at + 1]
            del argv[at:at + 2]
    no_verify = "--no-verify" in argv
    argv = [a for a in argv if a != "--no-verify"]
    if len(argv) != 2:
        sys.exit(__doc__)
    v, build = argv[0], Path(argv[1])
    variant = variants.get(v)
    out = build / "variant"
    header = GENERATED_HEADER.format(v=v, gid=variant["game_id"], rev=variant["revision"])
    report = [header]
    hooks = [r for r in runtime_scan.scan(variants.REPO / "runtime") if r["kind"].startswith("hook:") and r["token"]]

    if v == variants.CANONICAL:
        table = variants.AddressTable.identity()
        sda = entry = None
        layout = {}
        stubs = (p1_character.CARD_PORTRAIT, p1_character.CARD_PORTRAIT, p1_character.stub_size())
    else:
        (e1_dol, e1_rels), (tg_dol, tg_rels) = verify_variant.load_images(variant, opts)
        base_table = variants.address_table(variant, opts.get("--map"))
        tg = Image(tg_dol, tg_rels, base_table)
        computed = verify_variant.computed_values(variant, tg)
        stubs = computed[0][:3]
        table = variants.address_table(variant, None, computed)
        sda = tg.dol.sda_bases()
        init = tg.dol.init_registers()
        if (init.get(13), init.get(2)) != sda:
            sys.exit(f"{v}: main.dol's .sdata/.sdata2 give r13 0x{sda[0]:08X} r2 0x{sda[1]:08X}, but "
                     f"__init_registers sets {init.get(13)} / {init.get(2)}")
        entry = tg.dol.entry
        layout = tg.rel_layout()

    # nsmbw_va_table.inc / addr_map.tsv
    inc = [f"// {header}", "// {E1 start, E1 end (exclusive), target start} for NSMBW_VA(), sorted."]
    tsv = [f"# {header}", "# canonical_start\tcanonical_end\ttarget_start\t# source"]
    for a, b, t, src in table.rows:
        inc.append(f"{{0x{a:08X}u, 0x{b:08X}u, 0x{t:08X}u}},  // {src}")
        tsv.append(f"0x{a:08X}\t0x{b:08X}\t0x{t:08X}\t# {src}")
    write(out / "nsmbw_va_table.inc", "\n".join(inc) + "\n")
    write(out / "addr_map.tsv", "\n".join(tsv) + "\n")
    report.append(f"address table: {len(table.rows)} ranges ({'identity' if table.is_identity() else 'mapped'})")

    # nsmbw_va_tokens.h
    tok = [f"// {header}", "// The runtime's hook macros paste these: PPC_NATIVE_OVERRIDE(801A1138, ...) defines",
           "// func_<target> and registers 0x<target>. A token with no line here has no address on this",
           "// version, and using it fails to compile.", "#pragma once"]
    seen, missing = {}, []
    for r in sorted(hooks, key=lambda r: (r["token"].upper(), r["token"])):
        if r["token"] in seen:
            continue
        t = table.lookup(r["addr"])
        seen[r["token"]] = t
        if t is None:
            missing.append(r)
            tok.append(f"// NSMBW_VA_TOK_{r['token']}: no address ({r['file']}:{r['line']})")
        else:
            tok.append(f"#define NSMBW_VA_TOK_{r['token']} {token_target(r['token'], t)}")
    write(out / "nsmbw_va_tokens.h", "\n".join(tok) + "\n")
    report.append(f"hook tokens: {len(seen)} ({len(missing)} with no address)")

    # variant.h
    h = [f"// {header}", "#pragma once", f'#define NSMBW_VARIANT "{v}"', f"#define NSMBW_VARIANT_{v} 1",
         f'#define NSMBW_VARIANT_GAME_ID "{variant["game_id"]}"',
         f"#define NSMBW_VARIANT_REVISION {variant['revision']}",
         f"#define NSMBW_VARIANT_REGION '{variant['region']}'",
         f"#define NSMBW_VARIANT_P1_CHARACTER_STUBS 0x{stubs[1]:08X}u",
         f"#define NSMBW_VARIANT_MEM1_ARENA_HI 0x{verify_variant.arena_hi(variant):08X}u  // MEM1 end - the disc's FST"]
    if sda is not None:
        h += [f"#define NSMBW_VARIANT_SDA_BASE 0x{sda[0]:08X}u", f"#define NSMBW_VARIANT_SDA2_BASE 0x{sda[1]:08X}u",
              f"#define NSMBW_VARIANT_ENTRY 0x{entry:08X}u"]
        for k, (name, (image, bss, _end)) in enumerate(layout.items(), 1):
            h += [f"#define NSMBW_VARIANT_REL{k}_IMAGE 0x{image:08X}u  // {name}",
                  f"#define NSMBW_VARIANT_REL{k}_BSS 0x{bss:08X}u"]
    write(out / "variant.h", "\n".join(h) + "\n")

    if v != variants.CANONICAL:
        e1_starts, e1_names = verify_variant.read_function_map(variants.PROJECT / "MAP.txt")
        # The function map follows the code, so overrides.tsv (which is about the runtime's uses)
        # does not take a function out of it.
        map_table = variants.address_table(variant, None, computed, overrides=False)
        e1 = Image(e1_dol, e1_rels)
        results, _rows = verify_variant.equivalence(e1, tg, map_table.lookup, e1.dol.sda_bases(), sda,
                                                    e1_starts, e1_names)
        lines, map_report = function_map(e1_starts, e1_names, results, map_table, tg)
        write(out / "MAP.txt", "".join(lines))
        report += map_report
        game = Path(opts["--game"]) if "--game" in opts else variants.default_game_dir(variant)
        g = game.resolve().as_posix()
        first = min(image for image, _b, _e in layout.values())
        yml = f"""schema_version: 1
# {header}
workspace_root: {variants.REPO.resolve().as_posix()}

project:
  id: nsmbw-{variant['game_id'].lower()}
  display_name: {variant['display_name']}
  game_id: {variant['game_id']}
  region: {variant['region']}
  base_manifest_format: nsmbw-recomp-base-manifest
  base_manifest_stem: nsmbw_base

memory:
  base: 0x80000000
  size: 0x01800000
  sda_base: 0x{sda[0]:08X}
  sda2_base: 0x{sda[1]:08X}

inputs:
  dol:
    path: {g}/main_patched.dol
  rel:
    path: {g}/nsmbw_linked.rel
    load_address: 0x{first:08X}

translation:
  entry_points:
    - 0x{entry:08X}
  function_map:
    path: {out.resolve().as_posix()}/MAP.txt
  allow_unsupported_instructions: false

runtime:
  native_registration_root: runtime/src
  native_abi_directories:
    - runtime/src/hle/gx
  # The runtime is written against E1 addresses; this moves the ones the translator reads from it.
  address_map: {out.resolve().as_posix()}/addr_map.tsv

output:
  root: generated-{v}
  functions: functions
  runtime_config: RuntimeConfig.h
  data_initializer: data_sections_init.cpp
  base_manifest: ../build/base-{v}/nsmbw_base_manifest.json
"""
        write(out / "recomp.yml", yml)
        report.append(f"recomp.yml: inputs from {g} (unpack_game.py + prelink_rels.py --variant {v}), "
                      f"output generated-{v}/")
    write(out / f"gen_{v}.txt", "\n".join(report) + "\n")
    print("\n".join(report[:6]))
    if missing:
        print(f"{len(missing)} hook token(s) have no address on {v}: see nsmbw_va_tokens.h")
    if no_verify or v == variants.CANONICAL:
        return
    code = verify_variant.run(v, dict(opts, **{"--out": str(out)}))
    if code:
        sys.exit(f"verify_variant.py: {v} is not proven; see {out / f'verify_{v}.txt'}")


if __name__ == "__main__":
    main()
